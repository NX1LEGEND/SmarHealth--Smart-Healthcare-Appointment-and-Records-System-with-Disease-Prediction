def create_sample_pdf(title, patient_name, doctor_name, test_results):
    """Generates a professional sample medical report PDF in memory."""
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors
        import io
        
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
        elements = []
        styles = getSampleStyleSheet()
        
        # Header
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontSize=18,
            textColor=colors.HexColor('#0d9488'),
            spaceAfter=6
        )
        elements.append(Paragraph("SMART HEALTHCARE CLINICAL DIAGNOSTIC LABS", title_style))
        elements.append(Paragraph(f"<b>Report:</b> {title}", styles['Heading2']))
        elements.append(Spacer(1, 10))
        
        # Patient info table
        patient_info = [
            ["Patient Name:", patient_name, "Date Conducted:", timezone.now().strftime("%B %d, %Y")],
            ["Referring Physician:", doctor_name, "Status:", "COMPLETED & VERIFIED"]
        ]
        t1 = Table(patient_info, colWidths=[130, 160, 120, 130])
        t1.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f1f5f9')),
            ('TEXTCOLOR', (0,0), (-1,-1), colors.HexColor('#1e293b')),
            ('FONTNAME', (0,0), (-1,-1), 'Helvetica'),
            ('FONTSIZE', (0,0), (-1,-1), 9),
            ('BOTTOMPADDING', (0,0), (-1,-1), 5),
        ]))
        elements.append(t1)
        elements.append(Spacer(1, 15))
        
        # Test results table
        res_data = [["Test Parameter", "Measured Value", "Standard Biological Reference", "Interpretation"]]
        for row in test_results:
            res_data.append(row)
            
        t2 = Table(res_data, colWidths=[170, 110, 150, 110])
        t2.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#0d9488')),
            ('TEXTCOLOR', (0,0), (-1,0), colors.whitesmoke),
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
            ('FONTSIZE', (0,0), (-1,0), 9),
            ('ALIGN', (0,0), (-1,-1), 'LEFT'),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e1')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
            ('BOTTOMPADDING', (0,0), (-1,-1), 6),
            ('TOPPADDING', (0,0), (-1,-1), 6),
        ]))
        elements.append(t2)
        elements.append(Spacer(1, 20))
        
        footer_text = "<i>Note: This is an official clinical diagnostic record generated by the Smart Healthcare System. For clinical correlation, consult your specialist.</i>"
        elements.append(Paragraph(footer_text, styles['Normal']))
        
        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()
    except Exception as e:
        # Fallback text file
        return f"Smart Healthcare Clinical Report\nTitle: {title}\nPatient: {patient_name}\nDoctor: {doctor_name}\nDate: {datetime.date.today()}\n".encode('utf-8')


